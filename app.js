async function restoreSession() {

    const gameId =
        localStorage.getItem(
            GAME_KEY
        );

    const playerId =
        localStorage.getItem(
            PLAYER_KEY
        );


    if (
        !gameId ||
        !playerId
    ) {

        return false;
    }


    try {

        const {
            data: foundGame
        } =
            await supabaseClient
                .from("games")
                .select("*")
                .eq("id", gameId)
                .maybeSingle();


        const {
            data: player
        } =
            await supabaseClient
                .from("players")
                .select("*")
                .eq("id", playerId)
                .maybeSingle();


        if (
            !foundGame ||
            !player
        ) {

            return false;
        }


        game =
            foundGame;

        me =
            player;


        await loadGameData();

        subscribeToGame();

        renderCurrentState();


        return true;


    } catch (error) {

        console.error(error);

        return false;
    }
}


// ============================================================
// DATEN LADEN
// ============================================================

async function loadGameData() {

    if (!game) {
        return;
    }


    const {
        data: playerData,
        error: playerError
    } =
        await supabaseClient
            .from("players")
            .select("*")
            .eq(
                "game_id",
                game.id
            )
            .order(
                "created_at",
                {
                    ascending: true
                }
            );


    if (playerError) {

        throw playerError;
    }


    players =
        playerData || [];


    const {
        data: voteData,
        error: voteError
    } =
        await supabaseClient
            .from("votes")
            .select("*")
            .eq(
                "game_id",
                game.id
            )
            .eq(
                "question_index",
                game.current_question
            );


    if (voteError) {

        throw voteError;
    }


    votes =
        voteData || [];
}


// ============================================================
// REALTIME
// ============================================================

function subscribeToGame() {

    if (
        !game ||
        !supabaseClient
    ) {

        return;
    }


    if (realtimeChannel) {

        supabaseClient.removeChannel(
            realtimeChannel
        );
    }


    realtimeChannel =
        supabaseClient
            .channel(
                "ww-game-" +
                game.id
            )

            .on(
                "postgres_changes",
                {
                    event: "*",
                    schema: "public",
                    table: "games",
                    filter:
                        "id=eq." +
                        game.id
                },
                refreshRealtime
            )

            .on(
                "postgres_changes",
                {
                    event: "*",
                    schema: "public",
                    table: "players",
                    filter:
                        "game_id=eq." +
                        game.id
                },
                refreshRealtime
            )

            .on(
                "postgres_changes",
                {
                    event: "*",
                    schema: "public",
                    table: "votes",
                    filter:
                        "game_id=eq." +
                        game.id
                },
                refreshRealtime
            )

            .subscribe();
}


async function refreshRealtime() {

    try {

        const {
            data: updatedGame,
            error
        } =
            await supabaseClient
                .from("games")
                .select("*")
                .eq(
                    "id",
                    game.id
                )
                .single();


        if (error) {

            throw error;
        }


        game =
            updatedGame;


        await loadGameData();

        renderCurrentState();


        if (
            game.status === "playing" &&
            me.is_host &&
            votes.length >= players.length &&
            players.length >= MIN_PLAYERS
        ) {

            await setResult();
        }


    } catch (error) {

        console.error(error);
    }
}


