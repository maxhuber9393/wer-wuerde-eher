async function createGame() {

    try {

        const name =
            getSavedName();

        if (!name) {

            renderNameScreen();

            return;
        }

        const button =
            $("createGameButton");

        button.disabled = true;

        button.textContent =
            "SPIEL WIRD ERSTELLT...";


        let createdGame = null;


        for (
            let attempt = 0;
            attempt < 10;
            attempt++
        ) {

            const code =
                createGameCode();

            const {
                data,
                error
            } =
                await supabaseClient
                    .from("games")
                    .insert({

                        code: code,

                        status: "lobby",

                        current_question: 0,

                        question_order:
                            shuffledQuestionIndexes()

                    })
                    .select()
                    .single();


            if (!error) {

                createdGame =
                    data;

                break;
            }
        }


        if (!createdGame) {

            throw new Error(
                "Das Spiel konnte nicht erstellt werden."
            );
        }


        const {
            data: player,
            error: playerError
        } =
            await supabaseClient
                .from("players")
                .insert({

                    game_id:
                        createdGame.id,

                    name: name,

                    device_id:
                        getDeviceId(),

                    is_host: true

                })
                .select()
                .single();


        if (playerError) {

            throw playerError;
        }


        game =
            createdGame;

        me =
            player;


        saveSession();

        await loadGameData();

        subscribeToGame();

        renderLobby();


    } catch (error) {

        console.error(error);

        alert(
            "Fehler beim Erstellen des Spiels:\n\n" +
            error.message
        );

        renderChoiceScreen();
    }
}


