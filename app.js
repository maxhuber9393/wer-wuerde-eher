async function setResult() {

    if (
        !me.is_host ||
        !game
    ) {

        return;
    }


    if (
        game.status !==
        "playing"
    ) {

        return;
    }


    if (
        votes.length < players.length
    ) {

        return;
    }


    const {
        data,
        error
    } =
        await supabaseClient
            .from("games")
            .update({
                status: "result"
            })
            .eq(
                "id",
                game.id
            )
            .select()
            .single();


    if (error) {

        console.error(error);

        return;
    }


    game =
        data;


    renderResult();
}


function renderResult() {

    setRound(
        game.current_question + 1
    );


    const counts =
        Object.fromEntries(
            players.map(
                player => [
                    player.id,
                    0
                ]
            )
        );


    votes.forEach(
        vote => {

            if (
                counts[
                    vote.voted_for
                ] !== undefined
            ) {

                counts[
                    vote.voted_for
                ]++;
            }
        }
    );


    const maxVotes =
        Math.max(
            ...Object.values(
                counts
            )
        );


    const winners =
        players.filter(
            player =>
                counts[
                    player.id
                ] === maxVotes
        );


    const winnerNames =
        winners
            .map(
                player =>
                    player.name
            )
            .join(" & ");


    const sortedPlayers =
        [...players].sort(
            (a, b) =>
                counts[b.id] -
                counts[a.id]
        );


    const screen =
        $("resultScreen");


    screen.innerHTML = `

        <div
            class="result-label"
        >
            DIE ENTSCHEIDUNG IST GEFALLEN
        </div>


        <div
            class="winner-card"
        >

            <div
                class="winner-crown"
            >
                ♛
            </div>


            <p>
                AM MEISTEN GENANNT
            </p>


            <h2>
                ${escapeHtml(
                    winnerNames
                )}
            </h2>


            <div
                class="winner-votes"
            >
                ${maxVotes}

                ${
                    maxVotes === 1
                        ? "Stimme"
                        : "Stimmen"
                }

            </div>

        </div>


        <div
            class="vote-summary"
        >

            ${
                sortedPlayers
                    .map(
                        player => `

                            <div
                                class="vote-row"
                            >

                                <span>
                                    ${escapeHtml(
                                        player.name
                                    )}
                                </span>

                                <strong>
                                    ${counts[
                                        player.id
                                    ]}
                                </strong>

                            </div>

                        `
                    )
                    .join("")
            }

        </div>


        ${
            me.is_host

                ? `

                    <button
                        id="nextMultiplayerButton"
                        class="primary-button"
                        type="button"
                    >
                        NÄCHSTE FRAGE
                        <span>→</span>
                    </button>

                `

                : `

                    <div
                        class="waiting-message"
                    >
                        DER HOST STARTET
                        DIE NÄCHSTE FRAGE...
                    </div>

                `
        }

    `;


    showScreen(screen);


    if (me.is_host) {

        $("nextMultiplayerButton").onclick =
            nextMultiplayerQuestion;
    }
}


