// ============================================================

async function nextMultiplayerQuestion() {

    if (!me.is_host) {

        return;
    }


    const next =
        game.current_question + 1;


    if (
        next >=
        questions.length
    ) {

        const {
            data,
            error
        } =
            await supabaseClient
                .from("games")
                .update({
                    status:
                        "finished"
                })
                .eq(
                    "id",
                    game.id
                )
                .select()
                .single();


        if (error) {

            console.error(error);

            return;
        }


        game =
            data;


        renderFinished();

        return;
    }


    try {

        const {
            data,
            error
        } =
            await supabaseClient
                .from("games")
                .update({

                    current_question:
                        next,

                    status:
                        "playing"

                })
                .eq(
                    "id",
                    game.id
                )
                .select()
                .single();


        if (error) {

            throw error;
        }


        game =
            data;


        await loadGameData();

        renderQuestion();


    } catch (error) {

        console.error(error);

        alert(
            "Die nächste Frage konnte nicht geladen werden:\n\n" +
            error.message
        );
    }
}


