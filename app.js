// ============================================================

async function joinGame(code) {

    try {

        if (code.length !== 6) {

            alert(
                "Bitte einen 6-stelligen Spielcode eingeben."
            );

            return;
        }


        const {
            data: foundGame,
            error
        } =
            await supabaseClient
                .from("games")
                .select("*")
                .eq("code", code)
                .maybeSingle();


        if (error) {

            throw error;
        }


        if (!foundGame) {

            alert(
                "Dieses Spiel wurde nicht gefunden."
            );

            return;
        }


        if (foundGame.status !== "lobby") {

            alert(
                "Dieses Spiel wurde bereits gestartet."
            );

            return;
        }


        const {
            data: existingPlayers,
            error: playersError
        } =
            await supabaseClient
                .from("players")
                .select("*")
                .eq(
                    "game_id",
                    foundGame.id
                )
                .order(
                    "created_at",
                    {
                        ascending: true
                    }
                );


        if (playersError) {

            throw playersError;
        }


        if (
            existingPlayers.length >=
            MAX_PLAYERS
        ) {

            alert(
                "Das Spiel ist bereits voll."
            );

            return;
        }


        let player =
            existingPlayers.find(
                p =>
                    p.device_id ===
                    getDeviceId()
            );


        if (!player) {

            const {
                data: newPlayer,
                error: insertError
            } =
                await supabaseClient
                    .from("players")
                    .insert({

                        game_id:
                            foundGame.id,

                        name:
                            getSavedName(),

                        device_id:
                            getDeviceId(),

                        is_host: false

                    })
                    .select()
                    .single();


            if (insertError) {

                throw insertError;
            }


            player =
                newPlayer;
        }


        game =
            foundGame;

        me =
            player;


        saveSession();

        await loadGameData();

        subscribeToGame();

        renderLobby();


    } catch (error) {

        console.error(error);

        alert(
            "Fehler beim Beitreten:\n\n" +
            error.message
        );
    }
}


