// ============================================================
// ABSTIMMEN
// ============================================================

async function castVote(playerId) {

    if (
        !game ||
        !me
    ) {

        return;
    }


    if (
        playerId ===
        me.id
    ) {

        return;
    }


    if (
        votes.some(
            vote =>
                vote.player_id ===
                me.id
        )
    ) {

        return;
    }


    try {

        const {
            data: existing
        } =
            await supabaseClient
                .from("votes")
                .select("id")
                .eq(
                    "game_id",
                    game.id
                )
                .eq(
                    "player_id",
                    me.id
                )
                .eq(
                    "question_index",
                    game.current_question
                )
                .limit(1);


        if (
            existing &&
            existing.length
        ) {

            return;
        }


        const {
            error
        } =
            await supabaseClient
                .from("votes")
                .insert({

                    game_id:
                        game.id,

                    player_id:
                        me.id,

                    question_index:
                        game.current_question,

                    voted_for:
                        playerId
                });


        if (error) {

            throw error;
        }


        await loadGameData();

        renderQuestion();


        if (
            me.is_host &&
            votes.length >= players.length
        ) {

            await setResult();
        }


    } catch (error) {

        console.error(error);

        alert(
            "Die Stimme konnte nicht gespeichert werden:\n\n" +
            error.message
        );
    }
}


